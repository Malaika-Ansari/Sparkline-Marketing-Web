/**
 * Actual Performance Metrics for a Post
 */
export interface ContentPerformance {
  id: string;
  postId: string;
  reach: number;
  impressions: number;
  likes: number;
  comments: number;
  shares: number;
  saves: number;
  clicks: number;
  views: number;
  linkClicks: number;
  leads: number;
  conversions: number;
  // Computed Deterministic Metrics
  engagementRate: number; // ((likes + comments + shares + saves) / reach or impressions) * 100
  ctr: number; // (clicks / impressions) * 100
  cvr: number; // (conversions / clicks) * 100
  totalInteractions: number;
  dataSource: 'manual_entry' | 'imported';
  lastUpdated: string;
}

